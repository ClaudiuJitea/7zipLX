#!/usr/bin/env bash
# Generate cmake/7zcore_sources.cmake from the upstream 7zz build rules.
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SRC="$ROOT/7z2606-src"
BUNDLE="$SRC/CPP/7zip/Bundles/Alone2"
OUT="$ROOT/cmake/7zcore_sources.cmake"
TMP="$(mktemp)"
trap 'rm -f "$TMP"' EXIT

make -C "$BUNDLE" -B -n -f makefile.gcc >"$TMP" 2>/dev/null
{
  # Reuse every C/C++ translation unit from the standalone 7zz build,
  # except the console UI.
  grep -E '^(g\+\+|gcc|cc) ' "$TMP" \
    | grep ' -c ' \
    | sed -E 's/.* ([^ ]+\.(c|cpp))$/\1/' \
    | sort -u \
    | while read -r p; do
        case "$p" in
          ../../UI/Console/*|../../UI/Console/*) continue ;;
        esac
        realpath -m --relative-to="$SRC" "$BUNDLE/$p"
      done
  # Agent layer (archive-folder browsing and in-archive operations).
  printf '%s\n' \
    CPP/7zip/UI/Agent/Agent.cpp \
    CPP/7zip/UI/Agent/AgentProxy.cpp \
    CPP/7zip/UI/Agent/ArchiveFolder.cpp \
    CPP/7zip/UI/Agent/ArchiveFolderOpen.cpp \
    CPP/7zip/UI/Agent/ArchiveFolderOut.cpp \
    CPP/7zip/UI/Agent/AgentOut.cpp \
    CPP/7zip/UI/Agent/UpdateCallbackAgent.cpp \
    CPP/7zip/UI/Common/WorkDir.cpp
} | awk '!seen[$0]++' > "$TMP.names"

{
  echo '# Generated by scripts/gen-7zcore-sources.sh. Do not edit by hand.'
  echo 'set(SEVENZIP_CORE_SOURCES'
  sed 's/^/  /; s/$/;/' "$TMP.names"
  echo ')'
} > "$OUT"
count="$(wc -l < "$TMP.names")"
rm -f "$TMP.names"
echo "Wrote $OUT with $count entries"
